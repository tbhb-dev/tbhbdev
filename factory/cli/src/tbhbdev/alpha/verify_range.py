"""Check agent attribution and signing headers across a local commit range."""

import argparse
import subprocess  # nosec B404
import sys

from tbhbdev.alpha.identity import trailers as identity_trailers
from tbhbdev.alpha.identity.commit import grammar as trailer_grammar
from tbhbdev.alpha.identity.commit import picking as identity_commit_picking
from tbhbdev.alpha.identity.commit import policy as identity_policy
from tbhbdev.alpha.terminal import terminal_text


def problems(
    author: str, committer: str, parents: int, *, signed: bool, message: str
) -> list[str]:
    """Return every failed rule using only parsed commit values.

    A merge commit is generated by Git or GitHub, so the email, noreply,
    trailer and sign-off rules skip it, but it still needs a signature. The
    commits it brings in are still in the range and are checked.
    """
    if parents > 1:
        return [] if signed else ["missing gpgsig header"]
    reasons = []
    email = identity_policy.ident_email(identity_policy.AGENT_IDENT)
    for role, address in (("author", author), ("committer", committer)):
        if address != email:
            reasons.append(f"{role} email is {address!r}; expected {email}")
        if address.lower().endswith("@users.noreply.github.com") or address.lower() == (
            "noreply@github.com"
        ):
            reasons.append(f"{role} uses a GitHub noreply address")
    if not signed:
        reasons.append("missing gpgsig header")
    if identity_policy.SIGNOFF.search(message):
        reasons.append(identity_policy.SIGNOFF_ERROR)
    reasons.extend(trailer_grammar.check_message(message))
    if identity_commit_picking.pick_refused(
        identity_trailers.llm_trailers(message), own=True
    ):
        reasons.append(f"missing {identity_trailers.KEY_GEN} trailer with model=")
    if parents != 1:
        reasons.append(f"expected one parent, found {parents}")
    return reasons


def identity_problems(author: str, committer: str, message: str) -> list[str]:
    """Require attribution trailers and match any Committed-by to the committer."""
    reasons = trailer_grammar.check_message(message)
    lines = message.splitlines()
    prefix = "Committed-by:"
    claimed_committers = [
        line.removeprefix(prefix).strip() for line in lines if line.startswith(prefix)
    ]
    recorded_committer = identity_policy.IDENT_DATE.sub("", committer)
    if any(not value or value != recorded_committer for value in claimed_committers):
        reasons.append("Committed-by must match the Git committer's name and email")
    if not any(line.startswith(f"{identity_trailers.KEY_GEN}:") for line in lines):
        if identity_policy.AGENT_EMAIL in map(
            identity_policy.ident_email, (author, committer)
        ):
            reasons.append(
                f"missing {identity_trailers.KEY_GEN} trailer for agent commit"
            )
        elif not claimed_committers:
            reasons.append(
                f"missing {identity_trailers.KEY_GEN} or Committed-by trailer"
            )
    return reasons


def inspect_commit(text: str, *, identity_only: bool = False) -> tuple[list[str], str]:
    """Parse a commit object, keeping continuation lines out of its headers."""
    headers, _, message = text.partition("\n\n")
    # A continuation starts with a space, so its key is empty and cannot add
    # an author, committer, signature or parent header.
    fields = [line.partition(" ") for line in headers.split("\n")]
    values = {}
    for key, _, value in fields:
        values.setdefault(key, value)
    author = values.get("author", "")
    committer = values.get("committer", "")
    if identity_only:
        reasons = identity_problems(author, committer, message)
    else:
        reasons = problems(
            identity_policy.ident_email(author),
            identity_policy.ident_email(committer),
            sum(key == "parent" for key, _, _ in fields),
            signed="gpgsig" in values or "gpgsig-sha256" in values,
            message=message,
        )
    subject = " ".join(message.lstrip("\n").partition("\n\n")[0].splitlines())
    return reasons, subject


def git_output(path: str, *args: str) -> str:
    """Read original Git objects as UTF-8 without newline translation."""
    # Fixed git executable and argv; no command string is interpreted.
    return subprocess.run(  # nosec B603 B607
        [
            "git",
            "--no-replace-objects",
            "-c",
            "core.fsmonitor=false",
            "-c",
            "core.pager=cat",
            "-C",
            path,
            *args,
        ],
        check=True,
        capture_output=True,
        text=False,
    ).stdout.decode(errors="replace")


def main(argv: list[str], prog: str) -> int:
    parser = argparse.ArgumentParser(prog=prog, description=__doc__)
    parser.add_argument("base", metavar="BASE")
    parser.add_argument("tip", metavar="TIP")
    parser.add_argument("-C", dest="path", default=".")
    parser.add_argument(
        "--identity-only",
        action="store_true",
        help="require valid identity trailers on non-merge commits",
    )
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return int(exc.code or 0)
    try:
        base, tip = (
            git_output(
                args.path,
                "rev-parse",
                "--verify",
                "--end-of-options",
                ref + "^{commit}",
            ).strip()
            for ref in (args.base, args.tip)
        )
        flags = ["--no-merges"] if args.identity_only else []
        commits = git_output(
            args.path,
            "rev-list",
            "--reverse",
            "--topo-order",
            *flags,
            f"{base}..{tip}",
            "--",
        ).splitlines()
        failed = 0
        for sha in commits:
            reasons, subject = inspect_commit(
                git_output(args.path, "cat-file", "commit", sha),
                identity_only=args.identity_only,
            )
            if reasons:
                failed += 1
                result = (
                    "FAIL " + "; ".join(terminal_text(why) for why in reasons) + " |"
                )
            else:
                result = "ok"
            display_sha = sha if args.identity_only else sha[:7]
            print(f"{display_sha} {result} {terminal_text(subject)}")
        print(f"verify-range: {len(commits)} commits, {failed} failed")
    except (OSError, subprocess.CalledProcessError) as exc:
        print(f"{prog}: {terminal_text(str(exc))}", file=sys.stderr)
        return 2
    return int(failed != 0)

"""Tests for rendering and validating the private gitleaks config."""

# gazelle:include_pytest_conftest false

import tomllib

import pytest

from tbhbdev import host_gitleaks

GITLEAKS = (
    '[extend]\npath = ".gitleaks.toml"\n\n[[rules]]\nid = "tbhb-private-canary"\n'
)
CANARY_WHY = "has no rule with the id tbhb-private-canary"
EXTEND_WHY = 'has no [extend] path = ".gitleaks.toml"'


@pytest.mark.parametrize(
    ("text", "why"),
    [
        (GITLEAKS, None),
        (
            GITLEAKS.replace(
                'id = "tbhb-private-canary"', "  id='tbhb-private-canary'  # canary"
            ),
            None,
        ),
        (GITLEAKS.replace('id = "', 'id = "x-'), CANARY_WHY),
        (GITLEAKS.replace('canary"', 'canary-2"'), CANARY_WHY),
        (GITLEAKS.replace('id = "', '# id = "'), CANARY_WHY),
        (GITLEAKS.replace('[extend]\npath = ".gitleaks.toml"\n', ""), EXTEND_WHY),
        (GITLEAKS.replace('path = ".gitleaks.toml"', 'path = "x.toml"'), EXTEND_WHY),
        (GITLEAKS.replace("[extend]\npath", "extend"), EXTEND_WHY),
        (f"{GITLEAKS}[[[\n", "isn't valid TOML"),
    ],
)
def test_the_private_config_check(text: str, why: str | None) -> None:
    assert host_gitleaks.gitleaks_problem(text) == why


def test_the_generated_config_numbers_its_rules_by_category() -> None:
    text = host_gitleaks.render_gitleaks(
        [
            host_gitleaks.Rule("private-repo", r"\bfirst\b"),
            host_gitleaks.Rule("checkout-path", r"/checkouts\b", (r"^~/",)),
            host_gitleaks.Rule("private-repo", r"\bsecond\b"),
        ]
    )
    assert host_gitleaks.gitleaks_problem(text) is None
    assert text.startswith(
        "# Generated by `tbhbdev host bootstrap`, which replaces any edit.\n\n"
        '[extend]\npath = ".gitleaks.toml"\n\n'
    )
    assert text.endswith('\\b"\n')
    assert tomllib.loads(text)["rules"] == [
        {
            "id": "tbhb-private-canary",
            "description": "The canary: the private config is in use",
            "regex": r"\btbhb-private-canary-[0-9a-f]{8}\b",
        },
        {
            "id": "private-repo-1",
            "description": "A private repository's name",
            "regex": r"\bfirst\b",
        },
        {
            "id": "checkout-path-1",
            "description": "A path into the workspace checkouts",
            "regex": r"/checkouts\b",
            "allowlists": [{"regexes": [r"^~/"]}],
        },
        {
            "id": "private-repo-2",
            "description": "A private repository's name",
            "regex": r"\bsecond\b",
        },
    ]

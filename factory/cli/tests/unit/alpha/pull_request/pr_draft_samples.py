SECTIONS = [
    pr_body.Section("Why", required=True, max_words=60),
    pr_body.Section("Behavior change", required=True, max_words=120),
    pr_body.Section("Decisions", required=False, max_words=120),
    pr_body.Section("Deviations from the task", required=False, max_words=80),
    pr_body.Section("Needs human judgment", required=False, max_words=100),
    pr_body.Section("Risk", required=False, max_words=80),
    pr_body.Section("Verification", required=True, max_words=150),
    pr_body.Section("Human steering", required=False, max_words=40),
]
SCHEMA: dict[str, object] = {
    "type": "object",
    "properties": {"base": {"type": "string"}},
}


def structure(text: str) -> list[pr_body.Problem]:
    """Check a draft's structure using in-memory policy."""
    data, body = frontmatter.parse_frontmatter(text)
    head = check_head(text, data, body, SCHEMA)
    if isinstance(head, pr_draft.Checked):
        return head.problems
    return checked_draft(head, check_body(head, SECTIONS, agent_identity.LINE)).problems



def test_replaceable(tmp_path: Path) -> None:
    hook = tmp_path / "h"
    assert git_shims.replaceable(hook)
    for mark in git_shims.REPLACEABLE:
        hook.write_text(f"#!/bin/sh\n{mark}\n")
        assert git_shims.replaceable(hook)
    hook.write_text("#!/bin/sh\nmine\n")
    assert not git_shims.replaceable(hook)
    hook.write_bytes(b"#!/bin/sh\n\xff\n# File generated by prek\n")
    assert git_shims.replaceable(hook)
    hook.write_bytes(b"#!/bin/sh\n\xff\n")
    assert not git_shims.replaceable(hook)
    hook.write_text("#!/bin/sh\n# File generated by prek\n")
    link = tmp_path / "link"
    link.symlink_to(hook)
    assert git_shims.replaceable(link)


def test_replaceable_refuses_what_is_not_a_file(tmp_path: Path) -> None:
    folder = tmp_path / "commit-msg"
    folder.mkdir()
    dangling = tmp_path / "post-commit"
    dangling.symlink_to(tmp_path / "missing")
    for hook in (folder, dangling):
        with pytest.raises(model.InstallError) as raised:
            git_shims.replaceable(hook)
        assert str(raised.value) == (
            f"{hook} is not a file; remove it and run the install again"
        )


def test_back_up_legacy(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(git_shims, "stamp", lambda: "T")
    legacy = tmp_path / "commit-msg.legacy"
    legacy.write_text("mine")
    git_shims.back_up_legacy(legacy)
    backup = tmp_path / "commit-msg.legacy.tbhb-backup.T"
    assert backup.read_text() == "mine"
    assert not legacy.exists()
    assert capsys.readouterr().err == (
        f"tbhbdev alpha install: moved {legacy} to {backup}; "
        "prek install -f would delete it\n"
    )


def identity_hook(world: World, name: str = "commit-msg", verb: str = "check") -> None:
    world.hooks.mkdir(exist_ok=True)
    git_shims.install_identity_hook(["prek"], world.repo, world.hooks, (name, verb))


def test_identity_hook_without_prek_hooks_for_its_stage(world: World) -> None:
    identity_hook(world)
    hook = world.hooks / "commit-msg"
    text = hook.read_text()
    assert git_templates.SHIM_MARK in text
    assert 'tbhbdev alpha identity check "$@"' in text
    assert hook.stat().st_mode & 0o777 == 0o755
    assert not (world.hooks / "commit-msg.prek").exists()
    assert world.prek_calls() == [["list", "--hook-stage", "commit-msg"]]


def test_identity_hook_chains_prek_for_its_stage(
    world: World, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.setattr(git_shims, "stamp", lambda: "T")
    world.stages("commit-msg")
    world.hooks.mkdir(exist_ok=True)
    (world.hooks / "commit-msg.legacy").write_text("someone's\n")
    (world.hooks / "commit-msg.prek").write_text("stale\n")
    identity_hook(world)
    assert "tbhbdev alpha identity check" in (world.hooks / "commit-msg").read_text()
    assert "File generated by prek" in (world.hooks / "commit-msg.prek").read_text()
    backup = world.hooks / "commit-msg.legacy.tbhb-backup.T"
    assert backup.read_text() == "someone's\n"
    assert not (world.hooks / "commit-msg.legacy").exists()
    assert world.prek_calls() == [
        ["list", "--hook-stage", "commit-msg"],
        ["install", "-f", "--hook-type", "commit-msg"],
    ]
    assert "moved" in capsys.readouterr().err


@pytest.mark.parametrize("mark", git_shims.SHIM_MARKS)
def test_identity_hook_drops_a_legacy_identity_shim(world: World, mark: str) -> None:
    world.hooks.mkdir(exist_ok=True)
    # Bytes that aren't UTF-8 don't stop it reading the mark.
    shim = f"#!/bin/sh\n{mark}\n".encode()
    (world.hooks / "commit-msg.legacy").write_bytes(b"\xff" + shim)
    world.stages("commit-msg")
    identity_hook(world)
    assert not (world.hooks / "commit-msg.legacy").exists()
    assert [p.name for p in world.hooks.iterdir() if "backup" in p.name] == []


